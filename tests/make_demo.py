import json
import sys
from pathlib import Path

import cv2

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

import simlib  # noqa: E402

OUT = HERE.parent / "demo"
OUT.mkdir(exist_ok=True)

world = simlib.make_map(2048, 1152, seed=7)
truth = {"cx": 1210.0, "cy": 640.0, "scale": 0.8, "angle": 5.0, "alpha": 1.1, "beta": 8.0, "seed": 3}
drone = simlib.make_drone(world, truth["cx"], truth["cy"], truth["scale"], truth["angle"], truth["alpha"],
                          truth["beta"], size=(400, 250), seed=truth["seed"])
cv2.imwrite(str(OUT / "map.png"), world)
cv2.imwrite(str(OUT / "drone.png"), drone)
(OUT / "truth.json").write_text(json.dumps(
    {"center_px_map": [truth["cx"], truth["cy"]], "drone_px_per_map_px": truth["scale"],
     "rotation_deg": truth["angle"], "note": "synthetic data generated by tests/make_demo.py"}, indent=2))
print("wrote", OUT)
